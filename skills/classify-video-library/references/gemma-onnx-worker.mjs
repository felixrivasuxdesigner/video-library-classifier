#!/usr/bin/env node
/**
 * gemma-onnx-worker.mjs
 *
 * Native ONNX Runtime Q4 worker for `onnx-community/embeddinggemma-2-ONNX`.
 * Runs natively on macOS Intel (darwin-x64 AVX2) and Apple Silicon (darwin-arm64)
 * without requiring PyTorch >=2.4 wheels.
 *
 * Modes:
 *   1. Pre-warm / Download model weights:
 *      node gemma-onnx-worker.mjs --warmup
 *   2. Batch encode texts + multimodal (image + 16kHz mono WAV) windows:
 *      node gemma-onnx-worker.mjs --input /path/request.json --output /path/response.json
 */
import fs from "node:fs";
import os from "node:os";
import { AutoConfig, AutoModel, AutoProcessor, env, load_image } from "@huggingface/transformers";

env.useWasmCache = false;
const MODEL_ID = process.env.GEMMA_ONNX_MODEL || "onnx-community/embeddinggemma-2-ONNX";

/**
 * Reads a 16kHz mono 16-bit PCM WAV file generated by ffmpeg into a Float32Array.
 */
function readWav16kMono(wavPath) {
  const buf = fs.readFileSync(wavPath);
  // Find "data" chunk header in WAV
  let offset = 12;
  while (offset < buf.length - 8) {
    const chunkId = buf.toString("ascii", offset, offset + 4);
    const chunkSize = buf.readUInt32LE(offset + 4);
    if (chunkId === "data") {
      const pcmStart = offset + 8;
      const pcmEnd = Math.min(buf.length, pcmStart + chunkSize);
      const numSamples = Math.floor((pcmEnd - pcmStart) / 2);
      const float32 = new Float32Array(numSamples);
      for (let i = 0; i < numSamples; i++) {
        float32[i] = buf.readInt16LE(pcmStart + i * 2) / 32768.0;
      }
      return float32;
    }
    offset += 8 + chunkSize;
  }
  throw new Error(`Invalid WAV file (no data chunk): ${wavPath}`);
}

async function main() {
  const args = process.argv.slice(2);
  const isWarmup = args.includes("--warmup");
  const textOnly = args.includes("--text-only");
  const inputIdx = args.indexOf("--input");
  const outputIdx = args.indexOf("--output");

  const inputPath = inputIdx !== -1 ? args[inputIdx + 1] : null;
  const outputPath = outputIdx !== -1 ? args[outputIdx + 1] : null;

  const req = inputPath ? JSON.parse(fs.readFileSync(inputPath, "utf-8")) : {};
  const needVisionOrAudio = !textOnly && (isWarmup || (req.windows && req.windows.length > 0));

  console.error(
    `[gemma-onnx] Cargando ${MODEL_ID} (dtype=q4, arch=${os.arch()}, multimodal=${needVisionOrAudio})...`
  );

  const config = await AutoConfig.from_pretrained(MODEL_ID);
  if (!needVisionOrAudio) {
    config.vision_config = null;
    config.audio_config = null;
  }

  const processor = await AutoProcessor.from_pretrained(MODEL_ID);
  const model = await AutoModel.from_pretrained(MODEL_ID, {
    config,
    dtype: "q4",
  });

  if (isWarmup) {
    const warmupInputs = await processor(["task: search result | query: wedding ceremony"]);
    const { sentence_embedding } = await model(warmupInputs);
    console.error(
      `[gemma-onnx] ✓ Modelo Q4 descargado y verificado en caché local. Vector shape: [${sentence_embedding.dims.join(", ")}]`
    );
    return;
  }

  const result = {
    text_embeddings: [],
    window_embeddings: {},
  };

  // 1. Encode texts in batches
  const texts = req.texts || [];
  if (texts.length > 0) {
    const batchSize = 16;
    for (let i = 0; i < texts.length; i += batchSize) {
      const slice = texts.slice(i, i + batchSize);
      const procInputs = await processor(slice);
      const { sentence_embedding } = await model(procInputs);
      const list = sentence_embedding.tolist();
      result.text_embeddings.push(...list);
    }
  }

  // 2. Encode multimodal windows (image + optional 16kHz audio)
  const windows = req.windows || [];
  for (let i = 0; i < windows.length; i++) {
    const w = windows[i];
    let imgVec = null;
    let audVec = null;

    if (w.frame_path && fs.existsSync(w.frame_path)) {
      const image = await load_image(w.frame_path);
      const procImg = await processor(null, image);
      const { sentence_embedding } = await model(procImg);
      imgVec = sentence_embedding.tolist()[0];
    }

    if (w.audio_path && fs.existsSync(w.audio_path)) {
      try {
        const audioData = readWav16kMono(w.audio_path);
        if (audioData.length > 1600) {
          const procAud = await processor(null, null, audioData);
          const { sentence_embedding } = await model(procAud);
          audVec = sentence_embedding.tolist()[0];
        }
      } catch (err) {
        // Ignore audio decode fallback on corrupted snippet
      }
    }

    if (imgVec && audVec) {
      const fused = new Array(imgVec.length);
      for (let d = 0; d < imgVec.length; d++) {
        fused[d] = 0.65 * imgVec[d] + 0.35 * audVec[d];
      }
      result.window_embeddings[w.id] = fused;
    } else if (imgVec) {
      result.window_embeddings[w.id] = imgVec;
    } else if (audVec) {
      result.window_embeddings[w.id] = audVec;
    } else {
      result.window_embeddings[w.id] = new Array(768).fill(0.0);
    }

    if ((i + 1) % 10 === 0 || i + 1 === windows.length) {
      console.error(`[gemma-onnx] Ventanas procesadas: ${i + 1}/${windows.length}`);
    }
  }

  if (outputPath) {
    fs.writeFileSync(outputPath, JSON.stringify(result), "utf-8");
  } else {
    process.stdout.write(JSON.stringify(result));
  }
}

main().catch((err) => {
  console.error("[gemma-onnx] Error:", err);
  process.exit(1);
});
